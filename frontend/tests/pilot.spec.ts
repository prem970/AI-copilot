import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import path from 'node:path'

test('account → PDF → review → persistence → source → deletion', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await page.getByLabel('Email', { exact: true }).fill('browser@example.test')
  await page.getByLabel('Password', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('incorrect')
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Hello, Browser' })).toBeVisible()
  await expect(page.getByText('Start by uploading')).toBeVisible()
  await page.getByRole('button', { name: 'Profile & consent', exact: true }).click()
  await page.getByLabel('Blood group', { exact: true }).selectOption('O+')
  await page.getByRole('button', { name: 'Save profile & consent', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('saved')
  await page.reload()
  await expect(page.getByLabel('Blood group', { exact: true })).toHaveValue('O+')
  await page.getByRole('button', { name: 'Documents & review', exact: true }).click()
  const file=path.resolve('../.runtime/e2e/report.pdf')
  execFileSync('../.venv/Scripts/python.exe', ['-c', "from reportlab.pdfgen import canvas; import sys; c=canvas.Canvas(sys.argv[1]); c.drawString(40,800,'Report Date: 2026-05-06'); c.drawString(40,775,'Fasting Blood Glucose: 138 mg/dL (70 - 99) [H]'); c.save()", file])
  await page.locator('input[type=file]').setInputFiles(file)
  await page.getByRole('button', { name: 'Upload document', exact: true }).click()
  await expect(page.getByText('awaiting review', { exact: true })).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.getByLabel('Value', { exact: true })).toHaveValue('138')
  await page.getByLabel('I checked the selected values').check()
  await page.getByRole('button', { name: 'Confirm selected records', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Document summary' })).toBeVisible()
  await page.getByRole('button', { name: 'Records & trends', exact: true }).click()
  await expect(page.getByText('Fasting Blood Glucose', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('138 mg/dL', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('138 mg/dL', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Health assistant', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ask about my records' })).toBeDisabled()
  await page.getByRole('button', { name: 'Documents & review', exact: true }).click()
  const source=await page.getByRole('link', { name: 'View report.pdf' }).getAttribute('href')
  const preview=await page.request.get(source!)
  expect(preview.status()).toBe(200)
  expect(preview.headers()['content-type']).toContain('application/pdf')
  await page.screenshot({ path: '../.runtime/e2e/portal-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../.runtime/e2e/portal-mobile-documents.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 720 })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete report.pdf' }).click()
  await expect(page.getByText('No documents on this page.')).toBeVisible()
  await page.getByRole('button', { name: 'Records & trends', exact: true }).click()
  await expect(page.getByText('Confirm laboratory results')).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  expect((await page.request.get(source!)).status()).toBe(401)
})

test('mobile sign-in layout stays inside the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../.runtime/e2e/portal-mobile.png', fullPage: true })
})
