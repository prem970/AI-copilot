import { test, expect } from '@playwright/test'

test('create account → signed-in profile → sign out → sign in with saved credentials', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Create your account' })).toBeVisible()
  await page.getByLabel('Full name', { exact: true }).fill('Signup Patient')
  await page.getByLabel('Email', { exact: true }).fill('signup@example.test')
  await page.getByLabel('Password', { exact: true }).fill('signup-test-password')
  await page.getByLabel('Confirm password', { exact: true }).fill('different-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Passwords do not match')
  await page.getByLabel('Confirm password', { exact: true }).fill('signup-test-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Hello, Signup' })).toBeVisible()
  await page.getByRole('button', { name: 'Profile & consent', exact: true }).click()
  await page.getByLabel('Blood group', { exact: true }).selectOption('O+')
  await page.getByRole('button', { name: 'Save profile & consent', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('saved')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByLabel('Full name', { exact: true }).fill('Replacement')
  await page.getByLabel('Email', { exact: true }).fill('signup@example.test')
  await page.getByLabel('Password', { exact: true }).fill('replacement-password')
  await page.getByLabel('Confirm password', { exact: true }).fill('replacement-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('already exists')
  await page.getByRole('button', { name: 'Sign in instead' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue('signup@example.test')
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('')
  await page.getByLabel('Password', { exact: true }).fill('signup-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save profile & consent' })).toBeVisible()
  await expect(page.getByLabel('Blood group', { exact: true })).toHaveValue('O+')
  // An independent browser session can access the same saved account.
  const other = await browser.newContext()
  try {
    const tab = await other.newPage()
    await tab.goto('http://127.0.0.1:5174')
    await tab.getByLabel('Email', { exact: true }).fill('signup@example.test')
    await tab.getByLabel('Password', { exact: true }).fill('signup-test-password')
    await tab.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(tab.getByRole('heading', { name: 'Hello, Signup' })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Blood group', { exact: true })).toHaveValue('O+')
  } finally { await other.close() }
})

test('account creation works in a narrow viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByLabel('Confirm password', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Sign in instead' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
})
